cases=[]
for row in clauses:
    ident=row[0]; parts=ident.split('-')
    if len(parts)==3 and parts[0]=='FR':
        group=parts[1]; idx=int(parts[2])-1
        if group not in DATA or idx>=len(DATA[group]): raise RuntimeError(ident)
        setup,action,expected=DATA[group][idx]
        cases.append({'id':'TC-'+ident,'source':ident,'requirement':row[1],'priority':row[2],'source_location':row[3],'setup':setup,'steps':action,'expected':expected,'evidence':'请求/响应及trace_id、相关数据库前后快照、必要的WS/Worker/ComfyUI日志；前端项附页面截图','status':'NOT_RUN','test_type':'目标验收用例；不冒充现有自动化测试'})
